export function accountLabel(accountId: string | null): string {
  if (!accountId) return '—'
  const account = accounts.find((item) => item.id === accountId)
  return account ? account.number : accountId.slice(0, 8)
}

export function customerName(customerId: string): string {
  return (
    customers.find((item) => item.id === customerId)?.full_name ?? customerId
  )
}

export function transactionById(id: string): Transaction | undefined {
  return transactions.find((item) => item.id === id)
}
